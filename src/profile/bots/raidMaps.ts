/**
 * Кратчайший путь по карте рейда (без начальной точки), как в старом приложении: алгоритм Дейкстры
 * с очередью, которая пересортировывается после каждого добавления. Точки перебираются по возрастанию номера,
 * поэтому из нескольких путей одной длины выбирается тот же, что и раньше.
 */
export function raidPath(raid: number, from: number, to: number): number[] {
	const vertices: Record<string, Record<string, number>> = {};
	for (const [point, next] of RAID_MAPS[raid - 1] ?? []) {
		const edges: Record<string, number> = {};
		for (const target of next) edges[target] = 1;
		vertices[point] = edges;
	}
	const start = String(from);
	const finish = String(to);
	const queue: { key: string; priority: number }[] = [];
	const enqueue = (priority: number, key: string) => {
		queue.push({ key, priority });
		queue.sort((a, b) => a.priority - b.priority);
	};
	const distances: Record<string, number> = {};
	const previous: Record<string, string | null> = {};
	for (const vertex in vertices) {
		distances[vertex] = vertex === start ? 0 : Infinity;
		enqueue(distances[vertex], vertex);
		previous[vertex] = null;
	}
	let path: string[] = [];
	while (queue.length) {
		let smallest: string | null = queue.shift()!.key;
		if (smallest === finish) {
			path = [];
			while (previous[smallest!]) {
				path.push(smallest!);
				smallest = previous[smallest!] ?? null;
			}
			break;
		}
		if (!smallest || distances[smallest] === Infinity) continue;
		for (const neighbor in vertices[smallest]) {
			const alt = distances[smallest]! + vertices[smallest]![neighbor]!;
			if (alt < distances[neighbor]!) {
				distances[neighbor] = alt;
				previous[neighbor] = smallest;
				enqueue(alt, neighbor);
			}
		}
	}
	return path.reverse().map(Number);
}
